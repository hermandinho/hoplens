import { type FrameworkCopy, NEXT_COPY } from "./framework";
import { type ReplayableRequest, redactHeaders } from "./traceview";

/*
 * "Copy as Vitest test": turns one captured request into a regression guard. The test replays the
 * request against the dev server, asserts the status, then reads the trace Hoplens recorded for it
 * (x-hoplens-trace header + GET /__hoplens/api/traces/:id) and asserts a query budget. Pure: no
 * signals, no DOM.
 */

export interface VitestSource {
  id: string;
  method: string;
  path: string;
  route?: string;
  status?: number;
  duration?: number;
  counts?: { db: number; fetch: number; cache: number };
}

export interface VitestOptions {
  /** Origin of the app the test should hit, e.g. "http://localhost:3000". */
  baseUrl: string;
  /** Warm p95 of the route, when known, with its sample size. */
  p95?: { ms: number; n: number };
  /** Capture time, for the header comment. */
  capturedAt?: Date;
  /** Framework wording (what to run, what "cold" means). Next.js when omitted. */
  copy?: Pick<FrameworkCopy, "runWith" | "coldSkipped">;
}

/** Headers that are per-connection or recomputed by fetch; replaying them only causes trouble. */
const DROP_HEADERS = new Set([
  "host",
  "connection",
  "content-length",
  "accept-encoding",
  "transfer-encoding",
  "keep-alive",
  "upgrade",
  "te",
  "trailer",
  "x-hoplens-run",
]);

/** Path + query of `url`, whether it is absolute or already relative. */
export function pathOf(url: string): string {
  const m = /^[a-z][a-z0-9+.-]*:\/\/[^/?#]*([^#]*)/i.exec(url);
  const rest = m ? m[1] || "/" : url.split("#")[0] || "/";
  return rest.startsWith("/") ? rest : `/${rest}`;
}

function q(s: string): string {
  return JSON.stringify(s);
}

/** A ready-to-paste Vitest file. Secrets in headers are dropped (with a comment), never inlined. */
export function toVitest(req: ReplayableRequest, src: VitestSource, opts: VitestOptions): string {
  const copy = opts.copy ?? NEXT_COPY;
  const method = req.method.toUpperCase();
  const label = `${method} ${src.route ?? src.path}`;
  const redacted = redactHeaders(req.headers, true);
  const headers: Record<string, string> = {};
  const dropped: string[] = [];
  for (const [k, v] of Object.entries(redacted)) {
    const key = k.toLowerCase();
    if (DROP_HEADERS.has(key) || key.startsWith(":")) continue;
    if (v !== req.headers[k]) {
      dropped.push(key);
      continue;
    }
    headers[key] = v;
  }

  // `redirect: "manual"`: the test is about this one hop. Following a captured 307 would assert the
  // final 200, and read x-hoplens-trace (and the budgets) off the redirect target's request.
  const init: string[] = [`method: ${q(method)}`, `redirect: "manual"`];
  if (Object.keys(headers).length > 0 || dropped.length > 0) {
    const lines = Object.entries(headers).map(([k, v]) => `        ${q(k)}: ${q(v)},`);
    for (const k of dropped) lines.push(`        // ${q(k)}: "...", // redacted when copied: add your own`);
    init.push(`headers: {\n${lines.join("\n")}\n      }`);
  }
  if (req.body !== undefined && req.body !== "") init.push(`body: ${q(req.body)}`);

  const c = src.counts;
  const io = c ? c.db + c.fetch : undefined;
  const budget =
    io === undefined
      ? [
          "    // No facts were recorded for this request, so there is no query budget to assert yet.",
          "    // Example: expect(trace.facts.counts.db + trace.facts.counts.fetch).toBeLessThanOrEqual(3);",
        ]
      : [
          `    // Query budget: when this test was copied the request made ${c?.db} DB quer${c?.db === 1 ? "y" : "ies"} and`,
          `    // ${c?.fetch} outgoing fetch${c?.fetch === 1 ? "" : "es"}. An N+1 loop or an extra call sneaking in fails here.`,
          `    expect(trace.facts.counts.db + trace.facts.counts.fetch).toBeLessThanOrEqual(${io});`,
        ];
  const durLimit = opts.p95 ? Math.max(1, Math.ceil(opts.p95.ms * 2)) : undefined;
  const timing =
    durLimit !== undefined && opts.p95
      ? [
          `    // Time budget: 2x the route's warm p95 (${opts.p95.ms.toFixed(1)}ms over ${opts.p95.n} request${opts.p95.n === 1 ? "" : "s"}),`,
          `    // loose on purpose so a busy machine does not flake it. ${copy.coldSkipped}`,
          `    if (!trace.facts.cold) expect(trace.duration).toBeLessThanOrEqual(${durLimit});`,
        ]
      : ["    // No warm p95 was known for this route when copied, so duration is not asserted."];
  const status = src.status;
  const when = opts.capturedAt ? ` on ${opts.capturedAt.toISOString()}` : "";
  const took = src.duration !== undefined ? `, ${src.duration.toFixed(1)}ms` : "";

  return `import { describe, expect, it } from "vitest";

// Generated by Hoplens from trace ${src.id} (${label}, ${status ?? "no status"}${took})${when}.
// It replays the request against your dev server, then reads what Hoplens recorded for it: every
// dev response carries an x-hoplens-trace header, and GET /__hoplens/api/traces/:id returns that
// trace with its facts (query/fetch counts, duration). ${copy.runWith}
// Hoplens is dev-only, so point BASE_URL at a dev server, not a production build.
const BASE_URL = process.env.HOPLENS_BASE_URL ?? ${q(opts.baseUrl.replace(/\/$/, ""))};

interface HoplensTrace {
  done: boolean;
  duration?: number;
  facts?: { cold: boolean; counts: { db: number; fetch: number; cache: number } };
}

/** The trace is finalized a moment after the response ends: poll until it is done. */
async function hoplensTrace(id: string, timeoutMs = 5000): Promise<HoplensTrace> {
  const until = Date.now() + timeoutMs;
  for (;;) {
    const res = await fetch(\`\${BASE_URL}/__hoplens/api/traces/\${encodeURIComponent(id)}\`);
    if (res.ok) {
      const t = (await res.json()) as HoplensTrace;
      if (t.done && t.facts) return t;
    }
    if (Date.now() > until) throw new Error(\`Hoplens trace \${id} not finished after \${timeoutMs}ms\`);
    await new Promise((r) => setTimeout(r, 50));
  }
}

describe(${q(label)}, () => {
  it("keeps its status and query budget", async () => {
    const res = await fetch(\`\${BASE_URL}${pathOf(req.url).replace(/[`\\]/g, "\\$&").replace(/\$\{/g, "\\${")}\`, {
      ${init.join(",\n      ")},
    });
    ${status !== undefined ? `expect(res.status).toBe(${status});` : "// No status was captured for this request."}
    await res.arrayBuffer(); // drain the body so the request (and its trace) completes

    const id = res.headers.get("x-hoplens-trace");
    expect(id, "no x-hoplens-trace header: is this a dev server with Hoplens enabled?").toBeTruthy();
    const trace = (await hoplensTrace(id as string)) as Required<HoplensTrace>;

${budget.join("\n")}

${timing.join("\n")}
  });
});
`;
}
